import fs from "node:fs/promises";
import path from "node:path";

// Fixtures that aren't committed: large generated models, and files git can't
// or shouldn't hold (`node_modules/` is git-ignored). The harness writes them
// into every temporary fixture root (see e2e/lib/harness.ts), so they are
// always present; expectations.json lists them like the committed ones.
//
// Write them somewhere by hand: `npx tsx e2e/fixtures/gen.ts <dir>`.

// Deterministic pseudo-random numbers (mulberry32), so every run generates the
// same model.
function random(seed: number): () => number {
  let a = seed;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// A relative values catalog with `count` items in four clusters (the 120-item
// case froze the UI for 2.5–3 s per keystroke, QA #15).
function relativeValuesCatalog(count: number): string {
  const rand = random(count);
  const clusters = ["research", "software", "outreach", "operations"];
  const ids = Array.from(
    { length: count },
    (_, i) => `item${String(i + 1).padStart(3, "0")}`
  );
  const dists = ids.map((id, i) => {
    if (i === 0) return `  ${id}: 1,`;
    const low = Math.round((0.1 + rand() * 20) * 10) / 10;
    const high = Math.round(low * (2 + rand() * 20) * 10) / 10;
    return `  ${id}: ${low} to ${high},`;
  });
  const items = ids.map(
    (id, i) =>
      `    { id: "${id}", name: "Item ${i + 1}", clusterId: "${clusters[i % clusters.length]}" },`
  );
  const clusterDefs = clusters.map(
    (c, i) =>
      `    { id: "${c}", name: "${c[0]?.toUpperCase()}${c.slice(1)}", recommendedUnit: "${ids[i]}" },`
  );
  return [
    `// Generated by e2e/fixtures/gen.ts: ${count} items in ${clusters.length} clusters.`,
    "",
    "dists = {",
    ...dists,
    "}",
    "",
    `@name("Large catalog (${count} items)")`,
    "catalog = {",
    `  title: "Large catalog (${count} items)",`,
    "  items: [",
    ...items,
    "  ],",
    "  clusters: [",
    ...clusterDefs,
    "  ],",
    `  recommendedUnit: "${ids[0]}",`,
    "  fn: {|a, b| [dists[a], dists[b]]},",
    "}",
    "",
  ].join("\n");
}

// Paths are relative to the fixtures root (e2e/fixtures).
export const GENERATED_FIXTURES: Record<string, () => string> = {
  "rv/large-120.squiggle": () => relativeValuesCatalog(120),
  // Never listed or served: hidden and ignored folders.
  "tree/.hidden/secret.squiggle": () =>
    "// In a hidden folder: Studio must never list or open it.\n\nsecret = 1\n",
  "tree/node_modules/ignored.squiggle": () =>
    "// In node_modules: Studio must never list or open it.\n\nignored = 1\n",
};

// Writes the generated fixtures into `root`. With `subfolder` (e.g. "rv"),
// `root` is a copy of that fixtures subfolder, and only its files are written.
export async function writeGeneratedFixtures(
  root: string,
  subfolder?: string
): Promise<string[]> {
  const prefix = subfolder ? `${subfolder.replace(/\/+$/, "")}/` : "";
  const written: string[] = [];
  for (const [rel, generate] of Object.entries(GENERATED_FIXTURES)) {
    if (!rel.startsWith(prefix)) continue;
    const target = path.join(root, rel.slice(prefix.length));
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, generate());
    written.push(rel);
  }
  return written;
}

if (process.argv[1] && import.meta.filename === path.resolve(process.argv[1])) {
  const dir = process.argv[2];
  if (!dir) {
    process.stderr.write("Usage: tsx e2e/fixtures/gen.ts <dir>\n");
    process.exit(2);
  }
  const written = await writeGeneratedFixtures(path.resolve(dir));
  process.stdout.write(`${written.join("\n")}\n`);
}
