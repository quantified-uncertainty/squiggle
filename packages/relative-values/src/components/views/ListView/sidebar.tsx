"use client";
import { FC, Fragment, useEffect, useState } from "react";

import { NumberShower, SquiggleViewer } from "@quri/squiggle-components";
import { result, SqValue } from "@quri/squiggle-lang";
import { RefreshIcon } from "@quri/ui";

import { Item } from "../../../types.js";
import { ModelEvaluator } from "../../../values/ModelEvaluator.js";
import { relativeValuesPairCharts } from "../../../values/pairCharts.js";
import { ItemName } from "../ItemName.js";
import { useRelativeValuesOptions } from "../RelativeValuesProvider.js";

interface TableRowProps {
  label: string;
  number: number;
}

const TableRow: React.FC<TableRowProps> = ({ label, number }) => (
  <Fragment key={label}>
    <div className="col-span-1 mt-1 py-1 text-left text-xs font-normal text-slate-500">
      {label}
    </div>
    <div className="col-span-2 py-1 pl-2 text-left text-slate-600">
      <NumberShower number={number} precision={2} />
    </div>
  </Fragment>
);

// Self-contained code for the "Open in Playground" link: the model followed by
// the pair's charts. (The sidebar's own charts don't re-run the model, see
// PairCharts.)
const buildSquiggleCode = ({
  modelCode,
  fnExpression,
  numeratorItem,
  denominatorItem,
}: {
  modelCode: string;
  fnExpression: string;
  numeratorItem: Item;
  denominatorItem: Item;
}) => {
  const toVarName = (id: string) => id.replace(/[^a-zA-Z0-9_]/g, "_");
  const numeratorItemName = toVarName(numeratorItem.id);
  const denominatorItemName = toVarName(denominatorItem.id);
  return `${modelCode}
// ------- AUTOGENERATED CODE -------
rvComparisonFn = ${fnExpression}
dists = rvComparisonFn(${JSON.stringify(numeratorItem.id)}, ${JSON.stringify(denominatorItem.id)})
value_${numeratorItemName} = Dist(dists[0])
value_${denominatorItemName} = Dist(dists[1])
valueRatio = value_${numeratorItemName} / value_${denominatorItemName}
medianDenominator = abs(median(value_${denominatorItemName}))
tickFormat = '10'
tickFormatObj = {tickFormat: tickFormat}

@name("Normalized Scatter Plot")
scatter = Plot.scatter(
  {
    xDist: SampleSet(value_${denominatorItemName} / medianDenominator),
    yDist: SampleSet(value_${numeratorItemName} / medianDenominator),
    xScale: Scale.symlog(
      { tickFormatObj, title: ${JSON.stringify(denominatorItem.name)} }
    ),
    yScale: Scale.symlog(
      { tickFormatObj, title: ${JSON.stringify(numeratorItem.name)} }
    ),
  }
)

@name("Debug")
debug = [
  scatter,
  Tag.name(
    [
      Tag.name(
        Plot.dist(value_${numeratorItemName}, { xScale: Scale.symlog() }),
        ${JSON.stringify(numeratorItem.name)}
      ),
      Tag.name(
        Plot.dist(value_${denominatorItemName}, { xScale: Scale.symlog() }),
        ${JSON.stringify(denominatorItem.name)}
      ),
    ],
    "Distributions"
  ),
]

@name("Ratio Distribution")
ratio = Plot.dist(
  {
    dist: valueRatio,
    xScale: Scale.symlog(tickFormatObj),
    yScale: Scale.symlog(tickFormatObj),
    showSummary: false,
  }
)

ratio
`;
};

// The pair's charts, from the evaluator's own comparison function (see
// `relativeValuesPairCharts`): the model isn't re-run, so models with numbers
// as values, with a trailing result expression or with imports all work.
const PairCharts: FC<{
  model: ModelEvaluator;
  numeratorItem: Item;
  denominatorItem: Item;
}> = ({ model, numeratorItem, denominatorItem }) => {
  const key = JSON.stringify([
    numeratorItem.id,
    numeratorItem.name,
    denominatorItem.id,
    denominatorItem.name,
  ]);
  const [charts, setCharts] = useState<{
    key: string;
    model: ModelEvaluator;
    value: result<SqValue, string>;
  }>();

  useEffect(() => {
    let cancelled = false;
    relativeValuesPairCharts(model, numeratorItem, denominatorItem).then(
      (value) => {
        if (!cancelled) setCharts({ key, model, value });
      },
      (e: unknown) => {
        if (!cancelled) {
          setCharts({
            key,
            model,
            value: {
              ok: false,
              value: e instanceof Error ? e.message : String(e),
            },
          });
        }
      }
    );
    return () => {
      cancelled = true;
    };
    // `key` covers the items.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [model, key]);

  if (!charts || charts.key !== key || charts.model !== model) {
    return <RefreshIcon className="animate-spin text-slate-400" />;
  }
  if (!charts.value.ok) {
    return (
      <div className="text-xs text-red-700" data-rv-chart-error="">
        {charts.value.value}
      </div>
    );
  }
  return <SquiggleViewer value={charts.value.value} />;
};

type Props = {
  model: ModelEvaluator;
  numeratorItem: Item;
  denominatorItem: Item;
};

export const ItemSideBar: FC<Props> = ({
  model,
  numeratorItem,
  denominatorItem,
}) => {
  const { getPlaygroundUrl } = useRelativeValuesOptions();
  const result = model.compare(numeratorItem.id, denominatorItem.id);
  if (!result.ok) {
    return <div>Result not found</div>;
  } else {
    const item = result.value;
    const squiggleCode =
      model.modelCode !== undefined && model.fnExpression !== undefined
        ? buildSquiggleCode({
            modelCode: model.modelCode,
            fnExpression: model.fnExpression,
            numeratorItem,
            denominatorItem,
          })
        : undefined;

    return (
      <div>
        <div className="mb-6 mt-2 flex items-center overflow-x-auto p-1">
          <span className="mr-1 whitespace-nowrap text-slate-500">value</span>
          <span className="whitespace-nowrap text-xl text-slate-500">(</span>
          <span className="ml-2 mr-2 whitespace-pre-wrap rounded-sm bg-slate-200 bg-opacity-80 px-1 text-center text-sm font-semibold text-slate-900">
            <ItemName item={numeratorItem} />
          </span>
          <span className="whitespace-nowrap px-1 text-xl text-slate-500">
            /
          </span>

          <span className="ml-2 mr-2 whitespace-pre-wrap rounded-sm bg-slate-200 px-1 text-center text-sm font-semibold text-slate-900">
            <span className="inline-block">
              <ItemName item={denominatorItem} />
            </span>
          </span>
          <span className="whitespace-nowrap text-xl text-slate-500">)</span>
        </div>

        <div className="xs mb-4 text-slate-500">
          An estimate of the value of{" "}
          <span className="font-semibold text-slate-700">
            {numeratorItem.name}
          </span>{" "}
          in terms of{" "}
          <span className="font-semibold text-slate-700">
            {denominatorItem.name}
          </span>
        </div>

        {model.canCompute ? (
          <PairCharts
            model={model}
            numeratorItem={numeratorItem}
            denominatorItem={denominatorItem}
          />
        ) : (
          // Precomputed values (e.g. a bundle) don't include distributions.
          <div className="text-xs text-slate-500">
            Distribution charts aren&apos;t available for precomputed values.
          </div>
        )}

        <div className="mb-10 mt-10 grid w-full grid-cols-6 gap-1">
          <TableRow label="median" number={item.median} />
          <TableRow label="mean" number={item.mean} />
          <TableRow label="p5" number={item.min} />
          <TableRow label="p95" number={item.max} />
          <TableRow label="uncertainty" number={item.uncertainty} />
        </div>

        {squiggleCode !== undefined && getPlaygroundUrl && (
          <a
            href={getPlaygroundUrl(squiggleCode)}
            className="text-slate-500 underline"
            target="_blank"
            rel="noreferrer"
          >
            Open in Playground
          </a>
        )}
      </div>
    );
  }
};
