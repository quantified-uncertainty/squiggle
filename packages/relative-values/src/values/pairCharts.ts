import { result, run, SqLambda, SqValue } from "@quri/squiggle-lang";

import { Item } from "../types.js";
import type { ModelEvaluator } from "./ModelEvaluator.js";

// Charts of one pair for the list view sidebar: the ratio distribution, a
// normalized scatter plot and both distributions.
//
// The model isn't re-run, and no code is appended to it: the evaluator's
// comparison function gives the pair's two values, a fixed helper (compiled
// once, like `pairFromValues`) turns them into sample sets with `Dist()`
// (so numbers work too), and the charts are a small standalone program over
// those samples. Models with numbers as values, a trailing result expression
// or imports all work, and chart errors never point into the user's file.

const samplerCode = `
export pairSamples(a, b) = [SampleSet(Dist(a)), SampleSet(Dist(b))]
`;

const HELPER_LABEL = "Chart helper";

// Source id of the generated chart program (shown in its error messages).
export const PAIR_CHARTS_SOURCE_ID = "relative-values:pair-charts";

let samplerPromise: Promise<SqLambda> | undefined;

function getSampler(): Promise<SqLambda> {
  samplerPromise ??= (async () => {
    const output = await run(samplerCode);
    const bindings = output.getBindings();
    if (!bindings.ok) {
      throw new Error(
        `${HELPER_LABEL} failed to compile: ${bindings.value.toString()}`
      );
    }
    const sampler = bindings.value.get("pairSamples");
    if (sampler?.tag !== "Lambda") {
      throw new Error(`${HELPER_LABEL} is not a function`);
    }
    return sampler.value;
  })();
  return samplerPromise;
}

function samplesOf(value: SqValue | undefined): readonly number[] | undefined {
  if (value?.tag !== "Dist") return undefined;
  const dist = value.value;
  return dist.tag === "SampleSet" ? dist.getSamples() : undefined;
}

// A Squiggle list literal. Squiggle number literals have no "+" in exponents.
function listLiteral(samples: readonly number[]): string {
  return `[${samples.map((n) => String(n).replace("e+", "e")).join(", ")}]`;
}

/**
 * The Squiggle program of the pair's charts (a standalone program: the pair's
 * samples are literals in it). Its result is a dict of the ratio
 * distribution, the scatter plot and both distributions.
 */
export function pairChartsCode(
  samplesA: readonly number[],
  samplesB: readonly number[],
  nameA: string,
  nameB: string
): string {
  const a = JSON.stringify(nameA);
  const b = JSON.stringify(nameB);
  return `// The value of ${a} in terms of ${b}: charts generated by @quri/squiggle-relative-values.
valueA = SampleSet.fromList(${listLiteral(samplesA)})
valueB = SampleSet.fromList(${listLiteral(samplesB)})
medianB = abs(median(valueB))

@name("Ratio distribution")
@startOpen
ratio = Plot.dist(
  {
    dist: valueA / valueB,
    xScale: Scale.symlog(),
    yScale: Scale.symlog(),
    showSummary: false,
  }
)

@name("Normalized scatter plot")
@startOpen
scatter = Plot.scatter(
  {
    xDist: valueB / medianB,
    yDist: valueA / medianB,
    xScale: Scale.symlog({ title: ${b} }),
    yScale: Scale.symlog({ title: ${a} }),
  }
)

@name("Distributions")
distributions = [
  Tag.name(Plot.dist(valueA, { xScale: Scale.symlog() }), ${a}),
  Tag.name(Plot.dist(valueB, { xScale: Scale.symlog() }), ${b}),
]

{ ratio, scatter, distributions }
`;
}

/**
 * The charts for the value of `numerator` in terms of `denominator`, as a
 * standalone Squiggle program (see `pairChartsCode`); run it with
 * `PAIR_CHARTS_SOURCE_ID` as its source id. Errors are short messages:
 * "Comparison failed: …" for the model's comparison function, "Chart helper:
 * …" for the charts themselves.
 */
export async function relativeValuesPairCharts(
  evaluator: ModelEvaluator,
  numerator: Item,
  denominator: Item
): Promise<result<string, string>> {
  const environment = evaluator.environment;
  if (!evaluator.canCompute || !environment) {
    return {
      ok: false,
      value: "Charts aren't available for precomputed values",
    };
  }
  const pair = evaluator.comparePairValues(numerator.id, denominator.id);
  if (!pair.ok) {
    return { ok: false, value: `Comparison failed: ${pair.value}` };
  }
  const sampler = await getSampler();
  const sampled = sampler.call([pair.value[0], pair.value[1]], environment);
  if (!sampled.ok) {
    return { ok: false, value: `${HELPER_LABEL}: ${sampled.value.toString()}` };
  }
  const values =
    sampled.value.tag === "Array" ? sampled.value.value.getValues() : [];
  const samplesA = samplesOf(values[0]);
  const samplesB = samplesOf(values[1]);
  if (!samplesA || !samplesB) {
    return {
      ok: false,
      value: `${HELPER_LABEL}: expected two sample sets, got ${sampled.value.toString()}`,
    };
  }
  if (![...samplesA, ...samplesB].every(Number.isFinite)) {
    return {
      ok: false,
      value: `${HELPER_LABEL}: the values have non-finite samples`,
    };
  }
  return {
    ok: true,
    value: pairChartsCode(samplesA, samplesB, numerator.name, denominator.name),
  };
}
