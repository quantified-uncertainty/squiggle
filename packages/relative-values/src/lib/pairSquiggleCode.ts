import { Item } from "../types.js";

/**
 * Squiggle code for the list view sidebar: plots the comparison of two items,
 * evaluated in the scope of the model code.
 */
export const buildPairSquiggleCode = ({
  modelCode,
  fnExpression,
  numeratorItem,
  denominatorItem,
}: {
  modelCode: string;
  fnExpression: string;
  numeratorItem: Item;
  denominatorItem: Item;
}) => {
  const toVarName = (id: string) => id.replace(/[^a-zA-Z0-9_]/g, "_");
  const numeratorItemName = toVarName(numeratorItem.id);
  const denominatorItemName = toVarName(denominatorItem.id);
  return `${modelCode}
// ------- AUTOGENERATED CODE -------
rvComparisonFn = ${fnExpression}
dists = rvComparisonFn(${JSON.stringify(numeratorItem.id)}, ${JSON.stringify(denominatorItem.id)})
value_${numeratorItemName} = Dist(dists[0])
value_${denominatorItemName} = Dist(dists[1])
valueRatio = value_${numeratorItemName} / value_${denominatorItemName}
medianDenominator = abs(median(value_${denominatorItemName}))
tickFormat = '10'
tickFormatObj = {tickFormat: tickFormat}

@name("Normalized Scatter Plot")
scatter = Plot.scatter(
  {
    xDist: SampleSet(dists[1] / medianDenominator),
    yDist: SampleSet(dists[0] / medianDenominator),
    xScale: Scale.symlog(
      { tickFormatObj, title: ${JSON.stringify(denominatorItem.name)} }
    ),
    yScale: Scale.symlog(
      { tickFormatObj, title: ${JSON.stringify(numeratorItem.name)} }
    ),
  }
)

@name("Debug")
debug = [
  scatter,
  Tag.name(
    [
      Tag.name(
        Plot.dist(value_${numeratorItemName}, { xScale: Scale.symlog() }),
        ${JSON.stringify(numeratorItem.name)}
      ),
      Tag.name(
        Plot.dist(value_${denominatorItemName}, { xScale: Scale.symlog() }),
        ${JSON.stringify(denominatorItem.name)}
      ),
    ],
    "Distributions"
  ),
]

@name("Ratio Distribution")
ratio = Plot.dist(
  {
    dist: valueRatio,
    xScale: Scale.symlog(tickFormatObj),
    yScale: Scale.symlog(tickFormatObj),
    showSummary: false,
  }
)

ratio
`;
};
