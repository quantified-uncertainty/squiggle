// Regenerates the docs-derived reference files of the Squiggle Claude Code plugin
// (`claude-plugin/skills/squiggle/reference/`) from this package's content.
//
// Run with `pnpm gen:claude-plugin` (which builds content-collections first).
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { getDocumentationBundle, getLLMStyleGuide } from "../src/prompts.js";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(scriptDir, "../../..");
const referenceDir = join(repoRoot, "claude-plugin/skills/squiggle/reference");

function header(title: string, description: string) {
  return (
    `<!-- Generated by internal-packages/content/scripts/genClaudePlugin.ts. Do not edit by hand; run \`pnpm --filter @quri/content gen:claude-plugin\` instead. -->\n\n` +
    `# ${title}\n\n` +
    `> ${description}\n\n`
  );
}

function writeReference(filename: string, content: string) {
  const path = join(referenceDir, filename);
  // Normalize trailing whitespace so that regenerating is stable.
  const normalized =
    content
      .split("\n")
      .map((line) => line.trimEnd())
      .join("\n")
      .replace(/\n{4,}/g, "\n\n\n")
      .trim() + "\n";
  writeFileSync(path, normalized);
  console.log(
    `Wrote ${relative(repoRoot, path)} (${Math.round(normalized.length / 1024)} KB)`
  );
}

mkdirSync(referenceDir, { recursive: true });

writeReference(
  "language.md",
  header(
    "Squiggle language reference",
    "The complete Squiggle documentation bundle: common mistakes, style guide, language guides, and every builtin module and function. Search it (grep) rather than reading it top to bottom."
  ) + (await getDocumentationBundle())
);

writeReference(
  "style-guide.md",
  header(
    "Squiggle style guide",
    "Conventions for writing clear, well-calibrated Squiggle models."
  ) + (await getLLMStyleGuide())
);
